  const KEY = "cp-lang";
  let lang = "en";
  try { const v = localStorage.getItem(KEY); if (v === "ro" || v === "en") lang = v; } catch {}

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
    return s;
  }
  function serverMsg(m) {
    if (lang !== "en" || !m) return m;
    if (SERVER_EN[m]) return SERVER_EN[m];
    const v = /^Mai trebuie (\d+) vot\(uri\) ca să se poată închide\.$/.exec(m);
    if (v) return `${v[1]} more vote${v[1] === "1" ? "" : "s"} needed before voting can close.`;
    return m;
  }
  function apply(root) {
    const scopes = [root || document];
    (root || document).querySelectorAll("template").forEach(tp => scopes.push(tp.content));
    for (const sc of scopes) {
      sc.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
      sc.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
      sc.querySelectorAll("[data-i18n-ph]").forEach(el => { el.setAttribute("placeholder", t(el.dataset.i18nPh)); });
      sc.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    }
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-lang]").forEach(b => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  }
  function setLang(l) {
    if (l !== "en" && l !== "ro") return;
    lang = l;
    try { localStorage.setItem(KEY, l); } catch {}
    apply();
    window.dispatchEvent(new CustomEvent("cp-lang"));
  }
  window.I18N = { t, apply, setLang, serverMsg, get lang() { return lang; }, get locale() { return lang === "ro" ? "ro-RO" : "en-GB"; } };
